// Builds the flow editor bundle of BasecoatTheme:
//   webroot/js/basecoat-flow.js            React + React Flow + src/ (IIFE, minified, license comments kept)
//   webroot/css/basecoat-flow.css          React Flow styles + src/flow.css
//   webroot/js/basecoat-flow.LICENSES.txt  license of every npm package inside the bundle
// `node build.mjs --check` builds into memory and fails when the committed files differ (CI).
import { build } from 'esbuild';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const webroot = resolve(here, '../../webroot');
const check = process.argv.includes('--check');

const common = {
  bundle: true,
  minify: true,
  write: false,
  metafile: true,
  legalComments: 'eof',
  logLevel: 'warning',
  absWorkingDir: here,
};

const js = await build({
  ...common,
  entryPoints: ['src/index.jsx'],
  outfile: join(webroot, 'js/basecoat-flow.js'),
  format: 'iife',
  target: ['es2020'],
  jsx: 'automatic',
  define: { 'process.env.NODE_ENV': '"production"' },
  banner: { js: '/*! BasecoatTheme flow editor. Generated by resources/flow/build.mjs: do not edit. Licenses: basecoat-flow.LICENSES.txt */' },
});

const css = await build({
  ...common,
  entryPoints: ['src/flow.css'],
  outfile: join(webroot, 'css/basecoat-flow.css'),
  banner: { css: '/*! BasecoatTheme flow editor styles. Generated by resources/flow/build.mjs: do not edit. */' },
});

// Packages whose code ends up in the outputs, with their license text.
const packages = new Map();
for (const input of Object.keys({ ...js.metafile.inputs, ...css.metafile.inputs })) {
  const match = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
  if (!match || packages.has(match[1])) continue;
  const dir = join(here, 'node_modules', match[1]);
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const file = readdirSync(dir).find((name) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(name));
  packages.set(match[1], {
    version: pkg.version,
    license: pkg.license || 'see text',
    text: file ? readFileSync(join(dir, file), 'utf8').trim() : '(no license file in the package)',
  });
}
const rule = '='.repeat(72);
const notices = [
  'Third-party software bundled in basecoat-flow.js / basecoat-flow.css',
  '(generated by resources/flow/build.mjs from the packages in the bundle)',
  '',
  ...[...packages.keys()].sort().flatMap((name) => {
    const p = packages.get(name);
    return [rule, `${name} ${p.version} (${p.license})`, rule, p.text, ''];
  }),
].join('\n');

const outputs = [
  ...js.outputFiles.map((f) => [f.path, f.text]),
  ...css.outputFiles.map((f) => [f.path, f.text]),
  [join(webroot, 'js/basecoat-flow.LICENSES.txt'), notices],
];

let stale = 0;
for (const [path, text] of outputs) {
  const name = relative(resolve(here, '../..'), path);
  if (check) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== text) {
      console.error(`${name} is out of date: run npm --prefix resources/flow run build`);
      stale++;
    }
  } else {
    writeFileSync(path, text);
    console.log(`${name}  ${(Buffer.byteLength(text) / 1024).toFixed(1)} KB`);
  }
}
if (stale) process.exit(1);
if (check) console.log('Flow bundle is up to date.');
